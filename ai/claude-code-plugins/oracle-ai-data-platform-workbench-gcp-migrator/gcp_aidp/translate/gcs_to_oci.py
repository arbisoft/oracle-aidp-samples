"""`gs://` → `oci://` paths, and a reviewable Cloud Storage → OCI transfer job.

Paths are rewritten through a bucket map (GCS bucket → OCI bucket) taken from
the plan; a bucket the map does not name is flagged and left as written.

The copy itself is an rclone job: rclone has native
Google Cloud Storage and OCI Object Storage backends and gives parallel,
resumable, checksum-verified transfers. Nothing moves until a human runs it,
and it only ever reads from Cloud Storage.
"""
from __future__ import annotations

import re

_GS = re.compile(r"gs://([a-z0-9][a-z0-9._-]{1,221}[a-z0-9])(/[^\s'\"]*)?", re.IGNORECASE)


def rewrite_uri(uri: str, buckets: dict[str, str], namespace: str) -> str | None:
    """`gs://b/k` → `oci://<mapped b>@ns/k`, or None when `b` is not in the bucket map."""
    m = _GS.fullmatch(uri)
    if not m or m.group(1) not in buckets:
        return None
    return f"oci://{buckets[m.group(1)]}@{namespace}{m.group(2) or ''}"


def rewrite_text(text: str, buckets: dict[str, str], namespace: str) -> tuple[str, list[str], list[str]]:
    """Rewrite every `gs://` path in `text`. Returns (text, rewritten, unmapped)."""
    rewritten, unmapped = [], []

    def sub(m: re.Match) -> str:
        new = rewrite_uri(m.group(0), buckets, namespace)
        if new is None:
            unmapped.append(m.group(0))
            return m.group(0)
        rewritten.append(m.group(0))
        return new

    return _GS.sub(sub, text), rewritten, unmapped


def location_for(uris: list[str]) -> tuple[str | None, str]:
    """A Spark table LOCATION for BigQuery external-table source URIs: (gs:// dir, note).

    BigQuery takes a wildcard per URI; a Spark LOCATION is a directory. One URI
    whose wildcard is only in the last path segment maps to that directory.
    """
    if len(uris) != 1:
        return None, f"{len(uris)} source URIs; a Spark table has one LOCATION"
    uri = uris[0]
    head, _, last = uri.rpartition("/")
    if "*" in head:
        return None, f"wildcard in a directory of {uri!r}"
    if "*" in last:
        return head + "/", (f"LOCATION is the directory {head}/; every file in it is read, "
                            f"not only those matching {last!r}")
    return uri, ""


def build_transfer(bucket: str, oci_bucket: str, namespace: str, *,
                   oci_region: str = "<oci-region>", oci_profile: str = "DEFAULT",
                   compartment_ocid: str = "<compartment-ocid>") -> str:
    ns = namespace or "<your-oci-namespace>"
    return f"""#!/usr/bin/env bash
# Copy gs://{bucket}  →  oci://{oci_bucket}@{ns}
# Generated by gcp-aidp-migrator. Uses rclone (native GCS + OCI backends).
# Reads from Cloud Storage only. Review, then run:  bash {bucket}.transfer.sh
set -euo pipefail

# --- rclone config (written to a temp file; no global config touched) ---
CONF="$(mktemp)"
trap 'rm -f "$CONF"' EXIT
cat > "$CONF" <<'RCLONE'
# gcssrc uses Application Default Credentials, or the key file named by
# GOOGLE_APPLICATION_CREDENTIALS. A read-only role (Storage Object Viewer) is enough.
[gcssrc]
type = google cloud storage
env_auth = true

[ocidest]
type = oracleobjectstorage
provider = user_principal_auth
namespace = {ns}
region = {oci_region}
compartment = {compartment_ocid}
config_file = ~/.oci/config
config_profile = {oci_profile}
RCLONE

# --- ensure the destination bucket exists, then copy (never deletes) ---
rclone --config "$CONF" mkdir "ocidest:{oci_bucket}"
rclone --config "$CONF" copy "gcssrc:{bucket}" "ocidest:{oci_bucket}" \\
    --checksum --transfers 16 --fast-list --progress

echo "done: gs://{bucket} -> oci://{oci_bucket}@{ns}"
"""
